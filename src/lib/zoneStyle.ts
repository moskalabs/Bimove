/**
 * 공간(Zone)을 칠하는 색.
 *
 * 한이 Rayon 화면을 보내며 "회색 느낌으로" 라고 했다. 색이 있는 면은 도면 위에
 * 올린 **또 하나의 도형**처럼 보인다 — 중성 회색이라야 "이 범위" 라는 표시로
 * 읽힌다.
 *
 * ── 알파가 낮아야 하는 이유 ──
 *
 * 공간은 벽·가구 **위에** 깔린다. 진하게 칠하면 그 밑이 안 보여서, 어디를
 * 집었는지도 그 안에 뭐가 있는지도 못 본다. 비치는 정도로만 덮는다.
 *
 * ── 이름만 색을 남긴다 ──
 *
 * 면을 전부 회색으로 만들면 공간이 여럿일 때 서로 구분이 안 된다. Rayon 도
 * 면은 회색이고 이름은 색(빨강)이다. `color` prop 은 그래서 글자에 남긴다.
 *
 * ── 그리는 중과 완성본이 같아야 한다 ──
 *
 * 끌 때는 회색인데 손을 떼면 초록이 되면, 방금 본 게 그대로 들어간 건지
 * 의심하게 된다. `ZoneDrawOverlay` 와 `ZoneShape` 가 같이 쓴다.
 */

/** 면 채움. */
export const ZONE_FILL = 'rgba(100,108,120,0.16)'
/** 테두리. 점선인 건 "벽이 아니라 주석" 이라는 신호다. */
export const ZONE_STROKE = 'rgba(100,108,120,0.55)'
/** 면적 글자 — 이름보다 한 단계 여리게. */
export const ZONE_AREA_TEXT = '#5a6270'
