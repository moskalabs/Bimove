/**
 * 흑백(CAD) 모드의 **먹 농도**.
 *
 * 한이 "grayscale 로 보면 선이 잘 안 보인다" 는 말을 전해 왔다. 재 보니 값
 * 자체가 옅었다 — 흰 배경(255) 위에서 해치가 98, 글자가 79 였다. 거의 중간
 * 회색이다.
 *
 * ── 왜 적어 둔 값과 찍히는 값이 달랐나 ──
 *
 * 흑백 처리가 **두 겹**이었다. 도형이 제 색을 회색으로 칠하고(`#333` 등),
 * 그 위에 `.tl-canvas` 가 `filter: grayscale(1) contrast(1.15)` 를 또 걸었다.
 * contrast 는 값을 중간(128)에서 밀어내므로 `#333`(51) 은 39 로, `#666`(102)
 * 은 98 로 바뀐다. 즉 **코드에 적은 숫자가 화면의 숫자가 아니었다.** 그래서
 * 톤을 손보려 해도 얼마나 바뀔지 예측이 안 됐다.
 *
 * 그래서 contrast 를 걷어내고 **여기 적은 값이 그대로 찍히게** 했다.
 * `grayscale(1)` 은 남긴다 — 아직 흑백 분기가 없는 도형(문·창·치수 등)을
 * 거기서 받아 주기 때문이다.
 *
 * ── 왜 전부 검정으로 안 하나 ──
 *
 * 색이 사라진 자리를 **농도**가 대신해야 한다. 전부 검정이면 해치가 선과
 * 같은 무게가 되어 도면이 검은 덩어리가 된다 (종이공간 줌에서 실제로 겪었다 —
 * lib/dxfStroke 주석). 그래서 선 → 글자 → 해치 순으로 단을 둔다. 선은 읽으려는
 * 대상이고, 해치는 바탕 질감이다.
 */

export type GrayTones = {
  /** 도면선. 읽으려는 대상이라 가장 진하다. */
  line: string
  /** 글자. 선보다 한 단 여리게 — 안 그러면 글자가 선을 이긴다. */
  text: string
  /** 해치. 바탕 질감이라 제일 여리다. */
  hatch: string
}

/** 밝은 배경(흰 종이). 숫자는 명도 17 / 51 / 89. */
const LIGHT: GrayTones = { line: '#111111', text: '#333333', hatch: '#595959' }

/** 어두운 배경. 여기선 **밝을수록** 진하게 읽힌다 (명도 240 / 208 / 154). */
const DARK: GrayTones = { line: '#f0f0f0', text: '#d0d0d0', hatch: '#9a9a9a' }

export function grayTones(darkMode: boolean): GrayTones {
  return darkMode ? DARK : LIGHT
}
